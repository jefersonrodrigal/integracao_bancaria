@dataclass(frozen=True, slots=True)
class Instruction:
    code: str
    description: str
    obs: frozenset[str]
    printed: bool

    @property
    def uses_days(self) -> bool:
        return "A" in self.obs

    @property
    def bank_use(self) -> bool:
        return self.description == "USO DO BANCO"

    @property
    def supported(self) -> bool:
        # Obs B, C, D, E, F, I exigem campos adicionais ainda não modelados.
        return not self.bank_use and self.obs <= {"A", "G", "H"}


def _ins(code: str, description: str, obs: str = "", printed: bool = True) -> Instruction:
    return Instruction(code, description, frozenset(o for o in obs if o.isalpha()), printed)


