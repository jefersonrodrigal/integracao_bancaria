@dataclass(frozen=True, slots=True)
class Wallet:
    number: str
    code: str
    modality: Modality | None
    description: str
    obs: frozenset[str]
    supported: bool
    reason: str = ""

    @property
    def nosso_numero_by_bank(self) -> bool:
        # Nota 3 (p.18): escriturais enviam zerado (exceto 115); diretas: livre utilização.
        return self.modality is Modality.ESCRITURAL and self.number != "115"

    @property
    def requires_bank_range(self) -> bool:
        # Obs (D), Nota 5: somente nosso número dentro de faixa definida pelo Itaú.
        return "D" in self.obs

    @property
    def booklet(self) -> bool:
        return "CARNÊ" in self.description


